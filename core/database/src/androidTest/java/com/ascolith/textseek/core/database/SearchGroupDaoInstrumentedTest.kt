package com.ascolith.textseek.core.database

import android.content.Context
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.ascolith.textseek.core.database.dao.SearchGroupDao
import com.ascolith.textseek.core.database.dao.SearchSettingDao
import com.ascolith.textseek.core.database.entity.DbSearchGroup
import com.ascolith.textseek.core.database.entity.DbSearchSetting
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Instrumented integration tests for [SearchGroupDao] using Room.
 */
@RunWith(AndroidJUnit4::class)
class SearchGroupDaoInstrumentedTest {

    private lateinit var database: TextSeekDatabase
    private lateinit var searchGroupDao: SearchGroupDao
    private lateinit var searchSettingDao: SearchSettingDao

    @Before
    fun setup() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        database = Room.inMemoryDatabaseBuilder(context, TextSeekDatabase::class.java)
            .allowMainThreadQueries() // For testing only
            .build()
        searchGroupDao = database.searchGroupDao()
        searchSettingDao = database.searchSettingDao()
    }

    @After
    fun tearDown() {
        database.close()
    }

    @Test
    fun insertAndGetSearchGroup() = runBlocking {
        val searchGroup = DbSearchGroup(name = "instrumented", enabled = true, colorArgb = 0x123456)
        val id = searchGroupDao.create(searchGroup)
        val retrieved = searchGroupDao.get(id)
        assertEquals(searchGroup.name, retrieved?.name)
        assertEquals(searchGroup.enabled, retrieved?.enabled)
        assertEquals(searchGroup.colorArgb, retrieved?.colorArgb)
    }

    @Test
    fun createAssignsAnAutoGeneratedId() = runBlocking {
        val first = searchGroupDao.create(DbSearchGroup(name = "first", colorArgb = 1))
        val second = searchGroupDao.create(DbSearchGroup(name = "second", colorArgb = 2))
        assertEquals(first + 1, second)
    }

    @Test
    fun getReturnsNullWhenGroupDoesNotExist() = runBlocking {
        assertNull(searchGroupDao.get(999L))
    }

    @Test
    fun getSearchGroups_returnsAllInDescendingOrder() = runBlocking {
        val id1 = searchGroupDao.create(DbSearchGroup(name = "first", colorArgb = 1))
        val id2 = searchGroupDao.create(DbSearchGroup(name = "second", colorArgb = 2))
        val id3 = searchGroupDao.create(DbSearchGroup(name = "third", colorArgb = 3))
        val all = searchGroupDao.getSearchGroups().first()
        assertEquals(listOf(id3, id2, id1), all.map { it.uid })
    }

    @Test
    fun getSearchGroups_handlesEmptyDatabase() = runBlocking {
        assertEquals(emptyList<DbSearchGroup>(), searchGroupDao.getSearchGroups().first())
    }

    @Test
    fun updateSearchGroup() = runBlocking {
        val id = searchGroupDao.create(DbSearchGroup(name = "original", enabled = true, colorArgb = 0x111111))
        searchGroupDao.update(DbSearchGroup(uid = id, name = "updated", enabled = false, colorArgb = 0x222222))
        val retrieved = searchGroupDao.get(id)
        assertEquals("updated", retrieved?.name)
        assertEquals(false, retrieved?.enabled)
        assertEquals(0x222222, retrieved?.colorArgb)
    }

    @Test
    fun setEnabled_changesOnlyTheEnabledFlag() = runBlocking {
        val id = searchGroupDao.create(DbSearchGroup(name = "group", enabled = true, colorArgb = 0x333333))
        searchGroupDao.setEnabled(id, false)
        val retrieved = searchGroupDao.get(id)
        assertEquals(false, retrieved?.enabled)
        assertEquals("group", retrieved?.name) // Should remain unchanged
        assertEquals(0x333333, retrieved?.colorArgb) // Should remain unchanged
    }

    @Test
    fun deleteSearchGroup() = runBlocking {
        val id = searchGroupDao.create(DbSearchGroup(name = "to delete", colorArgb = 1))
        searchGroupDao.delete(id)
        assertNull(searchGroupDao.get(id))
    }

    @Test
    fun deleteAll_removesEveryGroup() = runBlocking {
        searchGroupDao.create(DbSearchGroup(name = "first", colorArgb = 1))
        searchGroupDao.create(DbSearchGroup(name = "second", colorArgb = 2))
        searchGroupDao.deleteAll()
        assertEquals(emptyList<DbSearchGroup>(), searchGroupDao.getSearchGroups().first())
    }

    @Test
    fun insertAll_insertsEveryGroupWithItsGivenId() = runBlocking {
        searchGroupDao.insertAll(
            listOf(
                DbSearchGroup(uid = 5L, name = "five", colorArgb = 5),
                DbSearchGroup(uid = 6L, name = "six", colorArgb = 6),
            ),
        )
        val all = searchGroupDao.getSearchGroups().first()
        assertEquals(listOf(6L, 5L), all.map { it.uid })
        assertEquals(listOf("six", "five"), all.map { it.name })
    }

    @Test
    fun deleteGroupChildren_removesOnlyThatGroupsSettings() = runBlocking {
        val groupId = searchGroupDao.create(DbSearchGroup(name = "group", colorArgb = 1))
        val otherGroupId = searchGroupDao.create(DbSearchGroup(name = "other", colorArgb = 2))
        searchSettingDao.create(DbSearchSetting(text = "mine", searchGroupId = groupId))
        searchSettingDao.create(DbSearchSetting(text = "theirs", searchGroupId = otherGroupId))
        searchSettingDao.create(DbSearchSetting(text = "ungrouped", searchGroupId = null))

        searchGroupDao.deleteGroupChildren(groupId)

        val remaining = searchSettingDao.getSearchSettings().first()
        assertEquals(setOf("theirs", "ungrouped"), remaining.map { it.text }.toSet())
        // The group itself survives; only its children were removed.
        assertNotNull(searchGroupDao.get(groupId))
    }

    @Test
    fun deleteGroupAndChildren_removesTheGroupAndItsSettings() = runBlocking {
        val groupId = searchGroupDao.create(DbSearchGroup(name = "group", colorArgb = 1))
        searchSettingDao.create(DbSearchSetting(text = "mine", searchGroupId = groupId))

        searchGroupDao.deleteGroupAndChildren(groupId)

        assertNull(searchGroupDao.get(groupId))
        assertEquals(emptyList<DbSearchSetting>(), searchSettingDao.getSearchSettings().first())
    }

    @Test
    fun deleteGroupAndChildren_leavesOtherGroupsUntouched() = runBlocking {
        val groupId = searchGroupDao.create(DbSearchGroup(name = "group", colorArgb = 1))
        val otherGroupId = searchGroupDao.create(DbSearchGroup(name = "other", colorArgb = 2))
        searchSettingDao.create(DbSearchSetting(text = "mine", searchGroupId = groupId))
        searchSettingDao.create(DbSearchSetting(text = "theirs", searchGroupId = otherGroupId))

        searchGroupDao.deleteGroupAndChildren(groupId)

        assertEquals(listOf(otherGroupId), searchGroupDao.getSearchGroups().first().map { it.uid })
        assertEquals(listOf("theirs"), searchSettingDao.getSearchSettings().first().map { it.text })
    }

    @Test
    fun deleteGroupAndChildren_withNoChildrenRemovesTheGroup() = runBlocking {
        val groupId = searchGroupDao.create(DbSearchGroup(name = "childless", colorArgb = 1))

        searchGroupDao.deleteGroupAndChildren(groupId)

        assertNull(searchGroupDao.get(groupId))
    }
}
